"""
Writes src/shared/Data/MeleeClips.luau (S1b's melee, tool and action clips, checklist 13.4)
from ual_retarget.py's JSON. Same data shape as UalClips.luau (gen_ual_module.py), its own
module so the two never collide.

Usage (from roblox/):
  python -P tools/ual/ual_retarget.py <ual.glb> melee.json Punch_Jab Punch_Cross Hit_Chest Hit_Head
  python -P tools/ual/gen_melee_clips.py melee.json src/shared/Data/MeleeClips.luau
Then run stylua on the output. Never edit MeleeClips.luau by hand.
"""
import json
import sys

ORDER = [
    "LowerTorso", "UpperTorso", "Head", "RightUpperArm", "RightLowerArm", "RightHand",
    "LeftUpperArm", "LeftLowerArm", "LeftHand", "RightUpperLeg", "RightLowerLeg", "RightFoot",
    "LeftUpperLeg", "LeftLowerLeg", "LeftFoot",
]

data = json.load(open(sys.argv[1]))
out_path = sys.argv[2]
lines = [
    "--!strict",
    "--[[",
    "\tMeleeClips: S1b's melee, tool and action clips retargeted from Quaternius's Universal",
    "\tAnimation Library (CC0; Zona assets-src/characters/ual) onto the R15 survivor",
    "\t(checklist 13.4). Generated by tools/ual/gen_melee_clips.py, never edited by hand.",
    "\tSame shape as UalClips: each key has a time and one rotation per part in PARTS order,",
    "\ta quaternion (x, y, z, w) in character space, the part's turn relative to its parent",
    "\tfrom the survivor rig's rest pose. LowerTorso adds its offset in studs. Domain/MeleeKeys",
    "\ttime-warps them onto Domain/MeleeTiming's marks.",
    "]]",
    "",
    "local MeleeClips = {}",
    "",
    "MeleeClips.PARTS = {",
]
for part in ORDER:
    lines.append(f'\t"{part}",')
lines += [
    "}",
    "",
    "export type Key = { t: number, p: { { number } } }",
    "export type Clip = { length: number, keys: { Key } }",
    "",
    "MeleeClips.clips = {",
]
for name, clip in data.items():
    lines.append(f"\t{name} = {{")
    lines.append(f'\t\tlength = {clip["length"]},')
    lines.append("\t\tkeys = {")
    for key in clip["keys"]:
        values = ["{ " + ", ".join(repr(x) for x in key["p"][part]) + " }" for part in ORDER]
        lines.append(f'\t\t\t{{ t = {key["t"]}, p = {{ ' + ", ".join(values) + " } },")
    lines.append("\t\t},")
    lines.append("\t},")
lines += ["} :: { [string]: Clip }", "", "return MeleeClips", ""]
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("written", out_path)
